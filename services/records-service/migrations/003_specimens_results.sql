  report_id CHAR(36) PRIMARY KEY,
  report_code VARCHAR(40) NOT NULL UNIQUE,
  order_id CHAR(36) NOT NULL,
  result_version_id CHAR(36) NOT NULL,
  patient_id CHAR(36) NOT NULL,
  specimen_id CHAR(36) NULL,
  panel_id CHAR(36) NULL,
  facility_id CHAR(36) NOT NULL,
  reported_by CHAR(36) NULL,
  verified_by CHAR(36) NULL,
  pathologist_id CHAR(36) NULL,
  registered_at DATETIME(6) NULL,
  collected_at DATETIME(6) NULL,
  received_at DATETIME(6) NULL,
  reported_at DATETIME(6) NULL,
  released_at DATETIME(6) NULL,
  report_status VARCHAR(32) NOT NULL,
  qr_token VARCHAR(120) NULL UNIQUE,
  qr_code_path VARCHAR(255) NULL,
  pdf_path VARCHAR(255) NULL,
  remarks TEXT NULL,
  CONSTRAINT fk_lab_report_order FOREIGN KEY (order_id) REFERENCES lab_order(order_id) ON DELETE RESTRICT,
  CONSTRAINT fk_lab_report_version FOREIGN KEY (result_version_id) REFERENCES result_version(result_version_id) ON DELETE RESTRICT,
  CONSTRAINT fk_lab_report_patient FOREIGN KEY (patient_id) REFERENCES patient(patient_id) ON DELETE RESTRICT,
  CONSTRAINT fk_lab_report_specimen FOREIGN KEY (specimen_id) REFERENCES specimen(specimen_id) ON DELETE RESTRICT,
  CONSTRAINT fk_lab_report_panel FOREIGN KEY (panel_id) REFERENCES test_panel(panel_id) ON DELETE RESTRICT,
  CONSTRAINT fk_lab_report_facility FOREIGN KEY (facility_id) REFERENCES facility_profile(facility_id) ON DELETE RESTRICT,
