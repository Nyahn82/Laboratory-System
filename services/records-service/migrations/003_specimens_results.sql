CREATE TABLE IF NOT EXISTS specimen (
  specimen_id CHAR(36) PRIMARY KEY,
  specimen_code VARCHAR(40) NOT NULL UNIQUE,
  accession_code VARCHAR(30) NOT NULL,
  order_id CHAR(36) NOT NULL,
  sample_type_id CHAR(36) NOT NULL,
  collected_by CHAR(36) NULL,
  collected_at DATETIME(6) NULL,
  received_by CHAR(36) NULL,
  received_at DATETIME(6) NULL,
  specimen_status VARCHAR(24) NOT NULL,
  specimen_condition VARCHAR(120) NULL,
  remarks TEXT NULL,
  rejection_reason VARCHAR(500) NULL,
  rejected_by CHAR(36) NULL,
  rejected_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_specimen_order FOREIGN KEY (order_id) REFERENCES lab_order(order_id) ON DELETE RESTRICT,
  CONSTRAINT fk_specimen_sample_type FOREIGN KEY (sample_type_id) REFERENCES sample_type(sample_type_id) ON DELETE RESTRICT,
  CONSTRAINT fk_specimen_collected_by FOREIGN KEY (collected_by) REFERENCES staff(staff_id) ON DELETE SET NULL,
  CONSTRAINT fk_specimen_received_by FOREIGN KEY (received_by) REFERENCES staff(staff_id) ON DELETE SET NULL,
  CONSTRAINT fk_specimen_rejected_by FOREIGN KEY (rejected_by) REFERENCES staff(staff_id) ON DELETE SET NULL,
  CONSTRAINT chk_specimen_status CHECK (specimen_status IN ('ACCESSIONED','COLLECTED','RECEIVED','REJECTED','IN_TESTING','PROCESSED','STORED')),
  KEY idx_specimen_order_status (order_id, specimen_status),
  KEY idx_specimen_accession (accession_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS result_version (
  result_version_id CHAR(36) PRIMARY KEY,
  order_id CHAR(36) NOT NULL,
  version_number INT NOT NULL,
  report_code VARCHAR(40) NOT NULL UNIQUE,
  status VARCHAR(32) NOT NULL,
  display_status VARCHAR(32) NOT NULL,
  publication_status VARCHAR(32) NOT NULL DEFAULT 'NOT_STARTED',
  patient_snapshot JSON NOT NULL,
  correction_of_version_id CHAR(36) NULL,
  submitted_by CHAR(36) NULL,
  submitted_at DATETIME(6) NULL,
  verified_by CHAR(36) NULL,
  verified_at DATETIME(6) NULL,
  released_by CHAR(36) NULL,
  released_at DATETIME(6) NULL,
  rejected_by CHAR(36) NULL,
  rejected_at DATETIME(6) NULL,
  rejection_reason TEXT NULL,
  content_hash CHAR(64) NULL,
  ciphertext_hash CHAR(64) NULL,
  protected_object_reference VARCHAR(255) NULL,
  ledger_transaction_id VARCHAR(255) NULL,
  revision BIGINT NOT NULL DEFAULT 1,
  created_by CHAR(36) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NULL,
  UNIQUE KEY uq_result_version_order_number (order_id, version_number),
  CONSTRAINT fk_result_version_order FOREIGN KEY (order_id) REFERENCES lab_order(order_id) ON DELETE RESTRICT,
  CONSTRAINT fk_result_version_correction FOREIGN KEY (correction_of_version_id) REFERENCES result_version(result_version_id) ON DELETE RESTRICT,
  CONSTRAINT chk_result_version_status CHECK (status IN ('DRAFT','QC_PENDING','QC_PASSED','QC_FAILED','REPEAT_REQUIRED','REFERRED','FOR_VERIFICATION','VERIFIED','REJECTED','RELEASED','SUPERSEDED','CANCELLED')),
  KEY idx_result_version_order_status (order_id, status),
  KEY idx_result_version_publication (publication_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS test_attempt (
  test_attempt_id CHAR(36) PRIMARY KEY,
  order_item_id CHAR(36) NOT NULL,
  order_id CHAR(36) NOT NULL,
  result_version_id CHAR(36) NOT NULL,
  test_id CHAR(36) NOT NULL,
  attempt_number INT NOT NULL,
  status VARCHAR(32) NOT NULL,
  methodology VARCHAR(150) NULL,
  result_item_id CHAR(36) NULL,
  repeat_test_id CHAR(36) NULL,
  started_by CHAR(36) NOT NULL,
  started_at DATETIME(6) NOT NULL,
  completed_by CHAR(36) NULL,
  completed_at DATETIME(6) NULL,
  UNIQUE KEY uq_test_attempt_number (order_item_id, result_version_id, attempt_number),
  CONSTRAINT fk_test_attempt_order_item FOREIGN KEY (order_item_id) REFERENCES order_item(order_item_id) ON DELETE RESTRICT,
  CONSTRAINT fk_test_attempt_order FOREIGN KEY (order_id) REFERENCES lab_order(order_id) ON DELETE RESTRICT,
  CONSTRAINT fk_test_attempt_version FOREIGN KEY (result_version_id) REFERENCES result_version(result_version_id) ON DELETE RESTRICT,
  CONSTRAINT fk_test_attempt_test FOREIGN KEY (test_id) REFERENCES test_catalog(test_id) ON DELETE RESTRICT,
  KEY idx_test_attempt_version_status (result_version_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS lab_result_item (
  result_item_id CHAR(36) PRIMARY KEY,
  report_id CHAR(36) NULL,
  result_version_id CHAR(36) NOT NULL,
  test_attempt_id CHAR(36) NULL,
  test_id CHAR(36) NULL,
  test_name_snapshot VARCHAR(150) NOT NULL,
  result_value VARCHAR(50) NOT NULL,
  numeric_value DECIMAL(18,6) NULL,
  unit_snapshot VARCHAR(50) NULL,
  reference_range_snapshot JSON NULL,
  flag VARCHAR(24) NULL,
  remarks TEXT NULL,
  sort_order INT NULL,
  source_result_item_id CHAR(36) NULL,
  created_by CHAR(36) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_result_item_version FOREIGN KEY (result_version_id) REFERENCES result_version(result_version_id) ON DELETE RESTRICT,
  CONSTRAINT fk_result_item_attempt FOREIGN KEY (test_attempt_id) REFERENCES test_attempt(test_attempt_id) ON DELETE RESTRICT,
  CONSTRAINT fk_result_item_test FOREIGN KEY (test_id) REFERENCES test_catalog(test_id) ON DELETE SET NULL,
  CONSTRAINT fk_result_item_source FOREIGN KEY (source_result_item_id) REFERENCES lab_result_item(result_item_id) ON DELETE RESTRICT,
  CONSTRAINT chk_result_flag CHECK (flag IS NULL OR flag IN ('Normal','Low','High','Critical Low','Critical High','Abnormal')),
  KEY idx_result_item_version_sort (result_version_id, sort_order),
  KEY idx_result_item_test (test_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS qc_check (
  qc_check_id CHAR(36) PRIMARY KEY,
  test_attempt_id CHAR(36) NOT NULL,
  outcome VARCHAR(8) NOT NULL,
  control_lot VARCHAR(80) NULL,
  notes TEXT NULL,
  performed_by CHAR(36) NOT NULL,
  performed_at DATETIME(6) NOT NULL,
  UNIQUE KEY uq_qc_check_attempt (test_attempt_id),
  CONSTRAINT fk_qc_check_attempt FOREIGN KEY (test_attempt_id) REFERENCES test_attempt(test_attempt_id) ON DELETE RESTRICT,
  CONSTRAINT chk_qc_outcome CHECK (outcome IN ('PASS','FAIL'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS repeat_test (
  repeat_test_id CHAR(36) PRIMARY KEY,
  source_attempt_id CHAR(36) NOT NULL,
  new_attempt_id CHAR(36) NULL,
  status VARCHAR(24) NOT NULL,
  reason TEXT NOT NULL,
  requested_by CHAR(36) NOT NULL,
  requested_at DATETIME(6) NOT NULL,
  completed_at DATETIME(6) NULL,
  CONSTRAINT fk_repeat_source_attempt FOREIGN KEY (source_attempt_id) REFERENCES test_attempt(test_attempt_id) ON DELETE RESTRICT,
  CONSTRAINT chk_repeat_status CHECK (status IN ('REQUIRED','IN_PROGRESS','COMPLETED','CLOSED')),
  KEY idx_repeat_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS referral (
