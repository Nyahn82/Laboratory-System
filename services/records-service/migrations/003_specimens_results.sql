  KEY idx_referral_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS result_interpretation (
  interpretation_id CHAR(36) PRIMARY KEY,
